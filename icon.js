// --- モーダル開閉制御 ---
function openToolModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.add("active");
    if (modalId === 'handbookModal') {
      updateHandbookContent();
    }
  }
}

function closeToolModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.remove("active");
  }
}

// --- ページめくり関数 ---
function changePage(type, direction) {
  currentPages[type] += direction;
  if (currentPages[type] < 1) currentPages[type] = 1;
  if (currentPages[type] > maxPages[type]) currentPages[type] = maxPages[type];

  const container = document.querySelector(`#${type}Modal`);
  const pages = container.querySelectorAll('.tool-page-content');
  
  pages.forEach(page => {
    page.classList.remove('active-page');
    if (page.getAttribute(`data-${type}-page`) == currentPages[type]) {
      page.classList.add('active-page');
    }
  });

  document.getElementById(`${type}Indicator`).innerText = `${currentPages[type]} / ${maxPages[type]}`;
  document.getElementById(`${type}Title`).innerText = modalTitles[type][currentPages[type] - 1];
}

